export function resoudreChoix(dict: Record<string, { fr: string; en: string }>, langue: Langue): Record<string, string> {
  const out: Record<string, string> = {}
  for (const [code, entree] of Object.entries(dict)) out[code] = entree[langue] ?? entree.fr
  return out
}

const LangueContext = createContext<Langue>('fr')

export function LangueProvider({ langue, children }: { langue: Langue; children: React.ReactNode }) {
  return <LangueContext.Provider value={langue || 'fr'}>{children}</LangueContext.Provider>
}

export function useLangue(): Langue {
  return useContext(LangueContext)
}

export function useChoix(dict: Record<string, { fr: string; en: string }>): Record<string, string> {
  const langue = useLangue()
  return resoudreChoix(dict, langue)
}

export function useT() {
  const langue = useLangue()
  return (cle: string): string => {
    const entree = DICT[cle]
    if (!entree) return cle
    return entree[langue] ?? entree.fr
  }
}
